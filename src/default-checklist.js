export const DEFAULT_CHECKLIST_ITEMS = SECTIONS.flatMap(([section, texts]) =>
  texts.map((text) => ({ section, text })));

export const DEFAULT_CHECKLIST = {
  kind: "opening",
  title: "Обход пиццерии",
  startTime: "08:30",
  dueMinutes: 90,
};

export async function ensureDefaultChecklist(ctx) {
  const target = ctx.cfg.checklistTopic;
  if (!target) return;
  const version = "2026-11-10.1";
  const marker = `default_checklist:${target.chatId}:${target.threadId}`;
  if ((await ctx.db.getSetting(marker)) === version) return;
  // Первую версию устанавливаем даже поверх старого чек-листа открытия этой темы.
  // Дальше администратор может менять шаблон: повторно маркер уже не даёт его перезаписать.
  await ctx.db.upsertChecklistTemplate({
    chatId: target.chatId,
    threadId: target.threadId,
    ...DEFAULT_CHECKLIST,
    items: DEFAULT_CHECKLIST_ITEMS,
  });
  await ctx.db.setSetting(marker, version);
}
